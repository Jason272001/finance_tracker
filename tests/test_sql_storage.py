"""Run SQLite coverage by default; opt into PostgreSQL on a disposable server.

KEEPERBMA_TEST_POSTGRES_URL must point at a test server. Each test gets its own
random schema and removes only that schema afterwards; no production URL is read.
"""
import os
import tempfile
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from unittest import mock

import pandas as pd
from sqlalchemy import create_engine, inspect, text

import core


class StorageCases:
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.schema = None
        if getattr(self, "postgres", False):
            self.schema = "keeperbma_test_" + uuid.uuid4().hex
            url = os.environ["KEEPERBMA_TEST_POSTGRES_URL"]
            self.admin_engine = create_engine(url)
            with self.admin_engine.begin() as connection:
                connection.execute(text(f'CREATE SCHEMA "{self.schema}"'))
            self.engine = create_engine(url, connect_args={"options": f"-csearch_path={self.schema}"})
        else:
            self.engine = create_engine("sqlite:///" + self.temp.name.replace("\\", "/") + "/test.db", connect_args={"timeout": 30})
        self.patcher = mock.patch.multiple(core, DB_IS_SQL=True, _ENGINE=self.engine)
        self.patcher.start()
        self.addCleanup(self._cleanup_storage)
        core.User._login_attempts.clear()
        self.uid = core.User().register("Creator", "secretpass123", email="creator@example.com", phone="5551234567", plan_code="basic", activate_without_payment=True)
        self.account = core.Account().add("Cash", "asset", "bank", user_id=self.uid)

    def _cleanup_storage(self):
        self.patcher.stop()
        self.engine.dispose()
        if self.schema:
            # This identifier was generated by this test, never supplied by a caller.
            with self.admin_engine.begin() as connection:
                connection.execute(text(f'DROP SCHEMA "{self.schema}" CASCADE'))
            self.admin_engine.dispose()
        self.temp.cleanup()

    def test_concurrent_income_preserves_all_rows_and_balance(self):
        def add_income(index):
            return core.Transaction().add("income", 10, self.account, "Freelance", user_id=self.uid)
        with ThreadPoolExecutor(max_workers=6) as pool:
            ids = list(pool.map(add_income, range(12)))
        self.assertEqual(len(set(ids)), 12)
        self.assertEqual(len(core.Transaction().by_user(self.uid)), 12)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 120)

    def test_failed_balance_posting_rolls_back_transaction(self):
        with mock.patch.object(core.Transaction, "_apply_postings", side_effect=RuntimeError("simulated posting failure")):
            with self.assertRaises(RuntimeError):
                core.Transaction().add("income", 100, self.account, user_id=self.uid)
        self.assertTrue(core.Transaction().by_user(self.uid).empty)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 0)

    def test_transfer_history_failure_rolls_back_both_balances(self):
        target = core.Account().add("Savings", "saving", "bank", user_id=self.uid)
        core.Account().update(self.account, user_id=self.uid, balance=100)
        with mock.patch.object(core.Transaction, "add", side_effect=RuntimeError("simulated history failure")):
            with self.assertRaises(RuntimeError):
                core.Account().transfer(self.account, target, 25, user_id=self.uid)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 100)
        self.assertEqual(core.Account().get(target, user_id=self.uid)["balance"], 0)

    def test_update_delete_and_transfer_commit_consistently(self):
        tx = core.Transaction()
        tid = tx.add("income", 100, self.account, user_id=self.uid)
        tx.update(tid, user_id=self.uid, amount=150)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 150)
        target = core.Account().add("Savings", "saving", "bank", user_id=self.uid)
        self.assertTrue(core.Account().transfer(self.account, target, 40, user_id=self.uid))
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 110)
        self.assertEqual(core.Account().get(target, user_id=self.uid)["balance"], 40)
        tx.delete(tid, user_id=self.uid)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], -40)
        self.assertEqual(len(tx.by_user(self.uid)), 1)  # neutral transfer history

    def test_tables_constraints_and_indexes_are_preserved(self):
        with self.engine.begin() as connection:
            connection.execute(text('CREATE INDEX keeperbma_account_name_test ON accounts (account_name)'))
        before = inspect(self.engine).get_pk_constraint("accounts")
        core.Account().update(self.account, user_id=self.uid, balance=5)
        after = inspect(self.engine).get_pk_constraint("accounts")
        self.assertEqual(before["constrained_columns"], ["account_id"])
        self.assertEqual(after["constrained_columns"], before["constrained_columns"])
        self.assertIn("keeperbma_account_name_test", [index["name"] for index in inspect(self.engine).get_indexes("accounts")])

    def test_cross_user_mutations_are_rejected(self):
        self.assertFalse(core.Account().update(self.account, user_id=self.uid + 1, balance=999))
        self.assertFalse(core.Account().delete(self.account, user_id=self.uid + 1))
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 0)

    def test_unscoped_snapshot_write_fails_closed(self):
        with self.assertRaises(RuntimeError):
            core._write_table("accounts", pd.DataFrame(columns=core.Account.cols))

    def test_cent_precision_is_preserved_and_fractional_cents_rejected(self):
        core.Transaction().add("income", 0.1, self.account, user_id=self.uid)
        core.Transaction().add("income", 0.2, self.account, user_id=self.uid)
        self.assertEqual(core.Account().get(self.account, user_id=self.uid)["balance"], 0.3)
        with self.assertRaises(ValueError):
            core.Transaction().add("income", 1.005, self.account, user_id=self.uid)
        self.assertEqual(len(core.Transaction().by_user(self.uid)), 2)


class SQLiteStorageTests(StorageCases, unittest.TestCase):
    pass


@unittest.skipUnless(os.getenv("KEEPERBMA_TEST_POSTGRES_URL"), "Disposable PostgreSQL URL not configured")
class PostgreSQLStorageTests(StorageCases, unittest.TestCase):
    postgres = True
